      '駅名の末尾の「駅」は削らず保持してください。「駅店」「駅前店」など店舗名の一部であればそのまま残してください。',
      '「〇〇駅から - 交通機関」などの補助説明は店舗名や金額に混ぜず、取引先となる駅名だけを転記してください。',
      '金額はそれぞれの取引に対応する円の整数を半角数字のみ（例：3808）で出力してください。¥・円・桁区切りカンマは金額列に含めず、残高・別の行の金額・日付の年を金額にしないでください。',
      '店舗名列には店名だけを書き、同じ行に表示された金額、日付、時刻、支払い状況、カード名を混ぜないでください。支払い通知画面では右側の金額とその下の取引日時を同一取引に対応させてください。',
      'PayPayのロゴや明確なPayPayクレジット表記と「クレジット VISA」が同じ取引の支払方法として確認できる場合は「PayPayクレジット」と書いてください。VISAだけでは発行カードを特定できないため、PayPayの根拠がなければ「VISA」など見えた文字のみを記載してください。',
      '支払方法は画面で明示された場合のみ出力してください。Suicaの利用履歴のように見えても画面に記載がない場合は「不明」。',
      '複数取引は省略も結合もせず、読み取れない値は「不明」としてください。'
