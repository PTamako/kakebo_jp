      'カード明細は店舗名・金額・利用日・支払回数が複数行や複数列に分かれていることがあります。まず画像内の取引ごとのまとまり（行・カード・区切り線・余白）を把握し、各まとまりの中にある対応する項目をすべて読んでください。項目の位置や並び順は画面・銀行によって異なるため、固定位置を前提にしないでください。',
      '特に日付を見落とさないでください。「9月6日」「9/6」「2026/09/06」のような小さな文字や薄い灰色の文字も、同じ取引の範囲内で探してください。日付が店名や金額から離れていても同じ取引なら対応付け、隣の取引の日付を流用しないでください。同じ日付の取引が複数あっても結合しないでください。',
      '日付が画像に「9月6日」「9/6」のように年なしで表示されている場合は、その表記を維持し、年を推測しないでください。日付の年が印字されていればその年を含めてください。日付が本当に見当たらない・読めない場合だけ「不明」としてください。「今日」「昨日」「一昨日」と表示されている場合は、元の文字を日付列へそのまま書いてください。現在の日付や画像の撮影日を推測しないでください。',
