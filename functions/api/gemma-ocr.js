      '日本語のカード・決済明細、Suica・PASMOなど交通系ICの利用履歴を読み取ってください。',
      '画像の1取引につき必ず1行、厳密に「日付,時刻,店舗名または駅名,金額,支払方法」の5列を半角カンマで出力してください。見出し・説明・Markdownは不要です。',
