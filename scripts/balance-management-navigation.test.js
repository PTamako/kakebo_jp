import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8')
const balance=read('src/pages/AssetsPage.vue')
const management=read('src/FinanceTools.vue')
const portfolio=read('src/SbiPortfolio.vue')
const reminders=read('src/InvestmentTransferReview.vue')
test('残高 is two selectable views, never a scrolling plan-manager page',()=>{
  assert.match(balance,/role="tablist"/)
  assert.match(balance,/@click="selectView\('funds'\)"/)
  assert.match(balance,/@click="selectView\('wallets'\)"/)
  assert.doesNotMatch(balance,/@click="selectView\('plans'\)"/)
  assert.doesNotMatch(balance,/振替予定|振替の確認|毎月の積立設定|振替と買付月/)
  assert.match(balance,/:active-view="activeView"/)
  assert.match(balance,/@summary="onPortfolioSummary"/)
  assert.match(balance,/@summary="onPrepaidSummary"/)
  assert.match(balance,/grid-template-columns:repeat\(2,minmax\(0,1fr\)\)/)
  assert.match(balance,/min-height:43px/)
})
test('管理 has its own 積立 page, with working plan and purchase month controls',()=>{
  assert.match(management,/>積立<\/button>/)
  assert.match(management,/managementTab === 'investment'/)
  assert.match(management,/<SbiPortfolio :api="props\.api" active-view="plans"/)
  assert.match(management,/<InvestmentTransferReview \/>/)
  assert.match(management,/grid-template-columns:repeat\(4,minmax\(0,1fr\)\)/)
  assert.match(portfolio,/v-show="activeView==='funds'"/)
  assert.match(portfolio,/v-show="activeView==='wallets'"/)
  assert.match(portfolio,/v-show="activeView==='plans'"/)
  assert.match(portfolio,/v-if="activeView==='plans'"/)
  assert.match(portfolio,/@click="editPlan\(p\)"/)
  assert.match(portfolio,/submitTransfer\(/)
  assert.match(portfolio,/newPurchaseMonth/)
  assert.match(portfolio,/sbi-transfer-disclosure/)
})
test('all due-transfer actions are preserved and do not use new storage',()=>{
  for(const marker of ['transferLoading','loadTransfers','transferStatusClass','transferDue','retryTransfer','dismissTransferReminder'])
    assert.ok(reminders.includes(marker),marker)
  assert.match(reminders,/pendingTransfers\.length/)
  assert.doesNotMatch(balance,/pendingTransfers\.length/)
  for(const filename of [balance,management,portfolio,reminders])
    assert.doesNotMatch(filename,/\bDROP TABLE\b|\bDELETE FROM\b|CREATE TABLE/i)
})
test('two SBI screenshot update and wallet history remain accessible',()=>{
  assert.match(portfolio,/@click="openBulk"/)
  assert.match(portfolio,/@change="readSbiScreen\(\$event,'profit'\)"/)
  assert.match(portfolio,/@change="readSbiScreen\(\$event,'positions'\)"/)
  assert.match(balance,/@open-history="openPrepaidHistoryDetails"/)
  assert.match(balance,/@open-card-settings="openCardSettings"/)
})
