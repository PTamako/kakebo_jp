import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8')
const finance=read('src/FinanceTools.vue')
const variable=read('src/VariableRecurringCosts.vue')
const list=read('src/OriginalFixedCostList.vue')

test('fixed costs show saved items by default; the editor is not mounted until requested',()=>{
 assert.match(finance,/const fixedPlanEditorOpen = ref\(false\)/)
 assert.match(finance,/@add="openNewFixedPlan"/)
 assert.match(finance,/v-if="fixedPlanEditorOpen" id="fixed-cost-editor"/)
 assert.match(finance,/fixedPlanEditorOpen.value = true/)
 assert.match(finance,/fixedPlanEditorOpen.value = false/)
 assert.match(finance,/add-label="固定費を追加"/)
 assert.match(finance,/@click="cancelPlanEdit">キャンセル/)
 assert.match(finance,/<OriginalFixedCostList default-open compact-header/)
 assert.match(list,/defaultOpen:\{type:Boolean,default:false\}/)
 assert.match(list,/<details class="recurring-list-disclosure" :open="defaultOpen">/)
 const firstList=finance.indexOf('<OriginalFixedCostList default-open')
 const firstReview=finance.indexOf('aria-label="固定費の記帳確認"')
 assert.ok(firstList>0&&firstReview>firstList,'saved list must precede review card')
})

test('variable costs open as a compact overview, not duplicate heading and two-level expanded form',()=>{
 assert.match(variable,/const expanded=ref\(false\),planEditor=ref\(false\),billEditor=ref\(false\)/)
 assert.doesNotMatch(variable,/v-if="inline" class="inline-heading"/)
 assert.match(variable,/<RecurringCostOverview title="変動金額"/)
 assert.match(variable,/@add="newPlan"/)
 assert.match(variable,/<form v-if="planEditor" ref="planEditorElement"/)
 assert.match(variable,/<form v-if="billEditor&&chosenPlan" ref="billEditorElement"/)
 assert.match(variable,/<details v-for="p in plans"/)
 assert.match(variable,/<RecurringFormSheet :open="active && planEditor"/)
 assert.match(variable,/<RecurringFormSheet :open="active && billEditor && !!chosenPlan"/)
 assert.match(variable,/class="recurring-date-pair"/)
 assert.match(finance,/<RecurringFormSheet :open="managementTab === 'plans' && recurringCostTab === 'fixed' && fixedPlanEditorOpen"/)
 assert.match(variable,/@click="openBill\(p\)"/)
 assert.match(variable,/@click="togglePlan\(p\)"/)
 assert.match(variable,/@click="editPlan\(p\)"/)
 assert.match(variable,/confirmBill/)
 assert.match(variable,/sourceType==='document'/)
 assert.doesNotMatch(variable,/<button type="button" :disabled="busy" @click="refresh">再読込/)
 assert.match(finance,/:refresh-key="variableRecurringRefreshKey"/)
 assert.match(finance,/variableRecurringRefreshKey.value\+\+/)
 assert.match(variable,/watch\(\(\)=>props.refreshKey,\(\)=>\{if\(props.inline\)void refresh\(\)\}\)/)
})

test('posting review is fixed-only; variable costs confirm bills on their own cards',()=>{
 const fixedPanelEnd=finance.indexOf('<section id="recurring-cost-panel-variable"')
 const common=finance.indexOf('class="recurring-common-review-area"')
 const lastVariable=finance.indexOf('<VariableRecurringCosts v-if="variableCostTabVisited"')
 assert.ok(common>lastVariable && lastVariable>fixedPanelEnd)
 assert.match(finance,/v-show="managementTab === 'plans' && recurringCostTab === 'fixed'" class="recurring-common-review-area"/)
 assert.match(finance,/<button v-if="recurringCostTab === 'fixed'"[^>]*@click="reviewRecurring"/)
 assert.doesNotMatch(finance,/@click="openVariableBillReview"/)
 assert.doesNotMatch(finance,/function openVariableBillReview/)
 assert.match(finance,/<VariableRecurringCosts v-if="variableCostTabVisited" inline/)
 assert.match(variable,/@click="openBill\(p\)"/)
 assert.match(variable,/chosenSaved\?\.status==='draft'/)
 assert.doesNotMatch(variable,/defineExpose\(\{openPendingReview\}\)/)
})
test('bill footer fits 3 actions on one row and shows one concise hint',()=>{
 const sheet=read('src/RecurringFormSheet.vue')
 assert.match(variable,/class="actions recurring-sheet-actions recurring-bill-actions"/)
 assert.match(sheet,/\.recurring-bill-actions\)\{grid-template-columns:repeat\(3,minmax\(0,1fr\)\)/)
 assert.match(variable,/下書きを保存/)
 assert.match(variable,/確認して記帳/)
 assert.match(variable,/v-else class="hint">金額と記帳日が揃うと自動記帳/)
 assert.match(variable,/v-else-if="chosenSaved\?\.sourceType==='document'" class="hint">文書助手の下書き/)
 assert.doesNotMatch(variable,/保存しただけでは支出になりません。文書助手ですでに記帳/)
})

