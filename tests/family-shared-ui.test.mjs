test('owner and member render exactly the same original pages and management tabs',()=>{
 assert.match(app,/<OriginalKakeiboPages :identity="familyIdentity"/)
 assert.match(family,/<OriginalKakeiboPages :identity="user"/)
 assert.match(shared,/<BottomNavigation :active-tab="activeTab"/)
 for(const view of ['EntryInputPage','LedgerPage','StatisticsPage','AssetsPage','ManagementPage'])
   assert.match(shared,new RegExp('<'+view+' '))
 assert.match(finance,/<FinanceManagementHeader v-model="managementTab"/)
 assert.doesNotMatch(finance,/<slot v-if="memberView&&\['plans','investment'\]/)
 assert.match(finance,/<UnifiedFixedCostManagement v-show=/)
 assert.match(finance,/:config="unifiedPlanConfig"/)
 assert.match(finance,/:api="unifiedInvestmentApi"/)
 assert.match(finance,/v-bind="unifiedCardProps"/)
 assert.equal((finance.match(/<OriginalOtherManagement /g)||[]).length,1)
 assert.match(finance,/:on-open-trash="memberView\?memberLoadTrash:/)
 for(const tab of ['list','stat','add','investments','finance'])
   assert.match(nav,new RegExp("'"+tab+"'"))
 for(const tab of ['cards','plans','investment','tools'])
   assert.match(tabs,new RegExp("'"+tab+"'"))
})
